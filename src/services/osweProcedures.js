export function catalogPolicies(records = []) {
  return osweProcedures.flatMap((procedure) => {
    const matches = records
      .filter((record) =>
        [procedure.title, procedure.legacyTitle]
          .filter(Boolean)
          .includes(record.title),
      )
      .sort(
        (a, b) =>
          Number(b.title === procedure.title) -
            Number(a.title === procedure.title) ||
          String(b.updatedAt || b.updated || "").localeCompare(
            String(a.updatedAt || a.updated || ""),
          ),
      );
    return matches.length ? [{ ...matches[0], title: procedure.title }] : [];
  });
}

export function filterProcedures(
  records,
  { category = "", owner = "", query = "" } = {},
) {
  const search = query.trim().toLowerCase();
  return records.filter(
    (p) =>
      (!category || p.category === category) &&
      (!owner || p.owner === owner) &&
      `${p.id || ""} ${p.title} ${p.category} ${p.owner} ${p.content || ""}`
        .toLowerCase()
        .includes(search),
  );
}
